const COLOR_MAP: Record<string, string> = {
  '1': '#221812', // Hair/dark shadow
  '2': '#e0a070', // Skin tan
  '3': '#2c3e50', // Royal Navy vest
  '4': '#f5f0e6', // White harem wrap
  '5': '#c0392b', // Flowing Red Sash
  '6': '#ecf0f1', // Steel blade
  '7': '#f39c12', // Golden hilt/sand
  '8': '#b8860b', // Sand armor/clay pot
  '9': '#74b9ff', // Crystal water/ice
}

/**
 * Universal Pixel Sprite Renderer with FlipX support
 */
export function drawPixelSprite(
  ctx: CanvasRenderingContext2D,
  matrix: SpriteMatrix,
  x: number,
  y: number,
  scale = 1,
  flipX = false,
  customColorMap?: Record<string, string>,
) {
  const roundedX = Math.round(x)
  const roundedY = Math.round(y)
  const colors = customColorMap || COLOR_MAP

  ctx.save()
  if (flipX) {
    const spriteWidth = (matrix[0]?.length || 0) * scale
    ctx.translate(roundedX + spriteWidth, roundedY)
    ctx.scale(-1, 1)
  } else {
    ctx.translate(roundedX, roundedY)
  }

  for (let row = 0; row < matrix.length; row++) {
    const line = matrix[row]
    for (let col = 0; col < line.length; col++) {
      const char = line[col]
      const color = colors[char]
      if (color) {
        ctx.fillStyle = color
        ctx.fillRect(col * scale, row * scale, scale, scale)
      }
    }
  }
  ctx.restore()
}
